package com.example.ai_notification_manager.utils;

import android.app.NotificationChannel;
import android.app.NotificationManager;
import android.app.PendingIntent;
import android.content.Context;
import android.content.Intent;
import android.os.Build;

import androidx.core.app.NotificationCompat;

import com.example.ai_notification_manager.InboxActivity;

public class CustomNotificationPublisher {

    private static final String CHANNEL_ID = "ai_custom_publisher_channel";
    private static final String TAG_CUSTOM_PUB = "AI_CUSTOM_PUB";

    public static void publishCustomNotification(Context context, String category, String title, String message, String sourceApp) {
        AppPreferences prefs = new AppPreferences(context);
        if (!prefs.isIncomingAlertsEnabled()) {
            return;
        }

        NotificationManager notificationManager = (NotificationManager) context.getSystemService(Context.NOTIFICATION_SERVICE);
        if (notificationManager == null) return;

        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            NotificationChannel channel = new NotificationChannel(
                    CHANNEL_ID,
                    "Smart Notifications (Lock Screen & Shade)",
                    NotificationManager.IMPORTANCE_HIGH
            );
            channel.setDescription("Categorized custom notifications generated by AI Notification Manager.");
            channel.setShowBadge(true);
            channel.enableVibration(true);
            notificationManager.createNotificationChannel(channel);
        }

        Intent intent = new Intent(context, InboxActivity.class);
        intent.putExtra("selected_category", category);
        intent.setFlags(Intent.FLAG_ACTIVITY_NEW_TASK | Intent.FLAG_ACTIVITY_CLEAR_TOP);
        PendingIntent pendingIntent = PendingIntent.getActivity(
                context,
                category.hashCode(),
                intent,
                PendingIntent.FLAG_UPDATE_CURRENT | PendingIntent.FLAG_IMMUTABLE
        );

        String contentTitle = "AI Notification Manager · " + category.toUpperCase();
        String contentText = sourceApp + " — " + title + (message != null && !message.isEmpty() ? "\n" + message : "");

        NotificationCompat.Builder builder = new NotificationCompat.Builder(context, CHANNEL_ID)
                .setSmallIcon(android.R.drawable.ic_popup_reminder)
                .setContentTitle(contentTitle)
                .setContentText(contentText)
                .setStyle(new NotificationCompat.BigTextStyle().bigText(contentText))
                .setAutoCancel(true)
                .setPriority(NotificationCompat.PRIORITY_HIGH)
                .setVisibility(NotificationCompat.VISIBILITY_PUBLIC) // Visible on Lock Screen
                .setContentIntent(pendingIntent);

        int notificationId = (int) System.currentTimeMillis();
        try {
            notificationManager.notify(TAG_CUSTOM_PUB, notificationId, builder.build());
        } catch (SecurityException ignored) {
            // POST_NOTIFICATIONS permission not granted on Android 13+
        }
    }
}
